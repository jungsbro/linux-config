#!/bin/bash

# usage ========================================================================
# sudo bash ./install_gpkg.sh jungs
# ==============================================================================

# setting the current user =====================================================
# CUR_USER="jungs"
CUR_USER=$1

if [[ $CUR_USER != "root" ]]; then
    while [[ -z $CUR_USER || ! -e /home/$CUR_USER ]]
    do
        echo "$CUR_USER not found"
        read -p "Please input username : " CUR_USER
    done
fi
# echo "your name : $CUR_USER"
# ==============================================================================

# update =======================================================================
apt update;
# ==============================================================================

# flatpak ======================================================================
apt install -y flatpak;
flatpak remote-add --if-not-exists flathub https://flathub.org/repo/flathub.flatpakrepo;
# ==============================================================================

# graphic driver ===============================================================
apt install -y nvidia-detect;
nvidia-detect;
apt install -y nvidia-driver;
# ==============================================================================

# korean =======================================================================
apt install -y fonts-nanum fonts-nanum-coding fonts-nanum-extra;
apt install -y uim uim-byeoru;
# ==============================================================================

# bottles ======================================================================
# ~/.local/share/applications/KakaoTalk.desktop
flatpak install -y flathub com.usebottles.bottles;
# ==============================================================================

# theme ========================================================================
apt install -y papirus-icon-theme;
# ==============================================================================

# ide ==========================================================================
apt install -y geany geany-plugins;

flatpak install flathub com.visualstudio.code;
# ==============================================================================

# file-manager =================================================================
apt install -y doublecmd-gtk;
# ==============================================================================

# web browser ==================================================================
apt install -y chromium;

apt install -y firefox;

wget https://dl.google.com/linux/direct/google-chrome-stable_current_amd64.deb;
apt install -y ./google-chrome-stable_current_amd64.deb;
# ==============================================================================

# ftp ==========================================================================
apt install -y filezilla;
# ==============================================================================

# file-sync ====================================================================
flatpak install -y flathub org.freefilesync.FreeFileSync;
# ==============================================================================

# snapshot =====================================================================
apt install -y timeshfit;
# ==============================================================================

# monitoring ===================================================================
# apt install -y conky;
# ==============================================================================

# bluelight ====================================================================
apt install -y redshift-gtk;
# ==============================================================================

# rdp ==========================================================================
apt install -y remmina;
