#!/bin/bash

# usage ========================================================================
# bash ${CORE_BIN_DIR}/system/config_swap.sh;
# ==============================================================================


# ENV ==========================================================================
# ------------------------------------------------------------------------------
# /core/linux/bin/system
CUR_DIR="$(dirname "$(realpath "$0")")"

ROOT_DIR="${CUR_DIR}/../../../.."

# core/linux/bin
CORE_BIN_DIR="${ROOT_DIR}/core/linux/bin"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
CUR_USER=${1};
HOME_DIR=$(eval echo ~${CUR_USER});

CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);

CUR_WMDE=$(ls /usr/bin/*session);
# ------------------------------------------------------------------------------
# ==============================================================================


# Func =========================================================================
function config_swap()
{
    # --------------------------------------------------------------------------
    local SYSCTL_PATH="/etc/sysctl.conf";
    local SWAP_CMD="vm.swappiness=10";
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    if [[ -e ${SYSCTL_PATH} ]] && [[ *"$(cat ${SYSCTL_PATH})"* != *"${SWAP_CMD}"* ]]; then
        echo "" >> ${SYSCTL_PATH};
        echo "${SWAP_CMD}" >> ${SYSCTL_PATH};
    fi
    # --------------------------------------------------------------------------
}
# ==============================================================================


# Main =========================================================================
config_swap;
# ==============================================================================
