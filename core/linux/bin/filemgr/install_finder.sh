#!/bin/bash

# finder =======================================================================
# bash ${BIN_DIR}/filemgr/install_finder.sh;
# ==============================================================================


# ENV ==========================================================================
# ------------------------------------------------------------------------------
# /core/linux/bin/filemgr
CUR_DIR="$(dirname "$(realpath "$0")")"

ROOT_DIR="${CUR_DIR}/../../../.."

# core/linux/bin
BIN_DIR="${ROOT_DIR}/core/linux/bin"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);

CUR_WMDE=$(ls /usr/bin/*-session);
# ------------------------------------------------------------------------------
# ==============================================================================



# func =========================================================================
# ------------------------------------------------------------------------------
# pcmanfm : LXDE 기본 파일 탐색기
# thunar : XFCE 기본 파일 탐색기
# caja : MATE 기본 파일 탐색기
# nemo : Cinnamon 기본 파일 탐색기
# nautilus : GNOME 기본 파일 탐색기
# ------------------------------------------------------------------------------

function install_finder_for_apt()
{
    if [[ *"${CUR_WMDE}"* == *"icewm"* ]]; then                                          # icewm (anitx)
        # ----------------------------------------------------------------------
        echo "";
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* != *"gnome"* ]] && [[ *"${CUR_WMDE}"* == *"openbox"* ]]; then   # lxde
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^pcmanfm$) ]] || apt install -y pcmanfm;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"xfce4"* ]]; then                                          # xfce4
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^thunar$) ]] || apt install -y thunar;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"mate"* ]]; then                                           # mate
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^caja$) ]] || apt install -y caja;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* != *"cinnamon"* ]] && [[ *"${CUR_WMDE}"* == *"gnome"* ]]; then  # gnome
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^nautilus$) ]] || apt install -y nautilus;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"cinnamon"* ]]; then                                        # cinnamon(mint)
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^nemo$) ]] || apt install -y nemo;
        # ----------------------------------------------------------------------
    fi
}

function install_finder_for_dnf()
{
    if [[ *"${CUR_WMDE}"* == *"icewm"* ]]; then                                          # icewm (anitx)
        # ----------------------------------------------------------------------
        echo "";
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* != *"gnome"* ]] && [[ *"${CUR_WMDE}"* == *"openbox"* ]]; then   # lxde
        # ----------------------------------------------------------------------
        echo "";
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"xfce4"* ]]; then                                          # xfce4
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^thunar$) ]] || dnf install -y thunar;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"mate"* ]]; then                                           # mate
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^caja$) ]] || dnf install -y caja;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* != *"cinnamon"* ]] && [[ *"${CUR_WMDE}"* == *"gnome"* ]]; then  # gnome
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^nautilus$) ]] || dnf install -y nautilus;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"cinnamon"* ]]; then                                        # cinnamon(mint)
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^nemo$) ]] || dnf install -y nemo;
        # ----------------------------------------------------------------------
    fi
}

function install_finder_for_pacman()
{
    if [[ *"${CUR_WMDE}"* == *"icewm"* ]]; then                                          # icewm (anitx)
        # ----------------------------------------------------------------------
        echo "";
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* != *"gnome"* ]] && [[ *"${CUR_WMDE}"* == *"openbox"* ]]; then   # lxde
        # ----------------------------------------------------------------------
        echo "";
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"xfce4"* ]]; then                                          # xfce4
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^thunar$) ]] || pacman -S --noconfirm thunar;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"mate"* ]]; then                                           # mate
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^caja$) ]] || pacman -S --noconfirm caja;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* != *"cinnamon"* ]] && [[ *"${CUR_WMDE}"* == *"gnome"* ]]; then  # gnome
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^nautilus$) ]] || pacman -S --noconfirm nautilus;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_WMDE}"* == *"cinnamon"* ]]; then                                        # cinnamon(mint)
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^nemo$) ]] || pacman -S --noconfirm nemo;
        # ----------------------------------------------------------------------
    fi
}
# ==============================================================================



# main : x86_64, i686, aarch64 =================================================
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then

    if [[ *"${CUR_VER}"* == *"debian"* ]] || [[ *"${CUR_VER}"* == *"ubuntu"* ]]; then
        # ----------------------------------------------------------------------
        install_finder_for_apt;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"CentOS"* ]] || [[ *"${CUR_VER}"* == *"rocky"* ]] || [[ *"${CUR_VER}"* == *"Fedora"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^epel-release) ]] || bash ${BIN_DIR}/pkgmgmt/update_repo.sh;
        # ----------------------------------------------------------------------
        install_finder_for_dnf;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"archlinux"* ]]; then
        # ----------------------------------------------------------------------
        install_finder_for_pacman
        # ----------------------------------------------------------------------
    fi

fi
# ==============================================================================


