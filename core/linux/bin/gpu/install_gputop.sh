# ENV ==========================================================================
# ------------------------------------------------------------------------------
# /core/linux/bin/gpu
CUR_DIR="$(dirname "$(realpath "$0")")"

ROOT_DIR="${CUR_DIR}/../../../.."

# core/linux/bin
CORE_BIN_DIR="${ROOT_DIR}/core/linux/bin"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
CUR_USER=${1};
HOME_DIR=$(eval echo ~${CUR_USER});

CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);

CUR_WMDE=$(ls /usr/bin/*session);
# ------------------------------------------------------------------------------
# ==============================================================================


# Func : x86_64, i686, aarch64 =================================================
function set_vendor()
{
    # --------------------------------------------------------------------------
    # pciutils is needed for lspci
    if [[ *"${CUR_VER}"* == *"archlinux"* ]]; then
        [[ -n $(pacman -Q | grep -i ^pciutils) ]] || pacman -S --needed --noconfirm pciutils;

    elif [[ *"${CUR_VER}"* == *"debian"* ]] || [[ *"${CUR_VER}"* == *"ubuntu"* ]]; then
        [[ -n $(apt list --installed | grep -i ^pciutils) ]] || apt install -y pciutils;

    elif [[ *"${CUR_VER}"* == *"CentOS"* ]] || [[ *"${CUR_VER}"* == *"rocky"* ]] || [[ *"${CUR_VER}"* == *"Fedora"* ]]; then
        [[ -n $(dnf list --installed | grep -i ^pciutils) ]] || dnf install -y pciutils;
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    # GPU 감지 (lspci 사용)
    local GPU_VENDOR=$(lspci | grep -E "VGA|3D" | grep -iE "nvidia|intel|amd|radeon")

    if echo "${GPU_VENDOR}" | grep -iq "nvidia"; then
        VENDOR="nvidia"

    elif echo "${GPU_VENDOR}" | grep -iq "amd\|radeon"; then
        VENDOR="radeon"

    elif echo "${GPU_VENDOR}" | grep -iq "intel"; then
        VENDOR="intel"

    else
        return
    fi
    # --------------------------------------------------------------------------
}


function install_gputop_for_pacman()
{
    # --------------------------------------------------------------------------
    if [[ *"${VENDOR}"* == *"nvidia"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^nvtop) ]] || pacman -S --needed --noconfirm nvtop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"radeon"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^radeontop) ]] || pacman -S --needed --noconfirm radeontop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"intel"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^intel-gpu-tools) ]] || pacman -S --needed --noconfirm intel-gpu-tools;
        # ----------------------------------------------------------------------
    fi
    # --------------------------------------------------------------------------
}


function install_gputop_for_apt()
{
    # --------------------------------------------------------------------------
    if [[ *"${VENDOR}"* == *"nvidia"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^nvtop) ]] || apt install -y nvtop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"radeon"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^radeontop) ]] || apt install -y radeontop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"intel"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^intel-gpu-tools) ]] || apt install -y intel-gpu-tools;
        # ----------------------------------------------------------------------
    fi
    # --------------------------------------------------------------------------
}


function install_gputop_for_rhel()
{
    # --------------------------------------------------------------------------
    # rmpfusion is needed for nvidia
    if [[ *"${VENDOR}"* == *"nvidia"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^nvtop) ]] || dnf install -y nvtop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"radeon"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^radeontop) ]] || dnf install -y radeontop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"intel"* ]]; then
        # ----------------------------------------------------------------------
        # [[ -n $(dnf list --installed | grep -i ^igt-gpu-tools) ]] || dnf install -y igt-gpu-tools;
        echo "Intel GPU tools may not be available in RHEL/CentOS repositories"
        # ----------------------------------------------------------------------
    fi
    # --------------------------------------------------------------------------
}


function install_gputop_for_dnf()
{
    # --------------------------------------------------------------------------
    if [[ *"${VENDOR}"* == *"nvidia"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^nvtop) ]] || dnf install -y nvtop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"radeon"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^radeontop) ]] || dnf install -y radeontop;
        # ----------------------------------------------------------------------

    elif [[ *"${VENDOR}"* == *"intel"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^igt-gpu-tools) ]] || dnf install -y igt-gpu-tools;
        # ----------------------------------------------------------------------
    fi
    # --------------------------------------------------------------------------
}
# ==============================================================================


# Main =========================================================================
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then

    # --------------------------------------------------------------------------
    bash ${CORE_BIN_DIR}/pkgmgmt/update_repo.sh;
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    set_vendor;
    if [[ -z "${VENDOR}" ]]; then
        return
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    if [[ *"${CUR_VER}"* == *"archlinux"* ]]; then
        # ----------------------------------------------------------------------
        install_gputop_for_pacman
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"debian"* ]] || [[ *"${CUR_VER}"* == *"ubuntu"* ]]; then
        # ----------------------------------------------------------------------
        install_gputop_for_apt;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"CentOS"* ]] || [[ *"${CUR_VER}"* == *"rocky"* ]]; then
        # ----------------------------------------------------------------------
        install_gputop_for_rhel;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"Fedora"* ]]; then
        # ----------------------------------------------------------------------
        install_gputop_for_dnf;
        # ----------------------------------------------------------------------
    fi
    # --------------------------------------------------------------------------

fi
