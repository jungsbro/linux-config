#!/bin/bash

# flatpak ======================================================================
# bash /core/linux/bin/pkgmgmt/install_flatpak.sh;
# ==============================================================================


# ENV ==========================================================================
CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);
# ==============================================================================


# Func : x86_64, i686, aarch64, ================================================
function add_flathub()
{
    # --------------------------------------------------------------------------
    if [[ *"$(flatpak remotes)"* == *"flathub"* ]]; then
        return
    fi
    # --------------------------------------------------------------------------

    flatpak remote-add --if-not-exists flathub https://flathub.org/repo/flathub.flatpakrepo;
}
# ==============================================================================


# Main =========================================================================
if [[ *"${CUR_VER}"* == *"debian"* ]] || [[ *"${CUR_VER}"* == *"ubuntu"* ]]; then
    # --------------------------------------------------------------------------
    [[ -n $(apt list --installed | grep -i ^flatpak) ]] || apt install -y flatpak;
    # --------------------------------------------------------------------------
elif [[ *"${CUR_VER}"* == *"CentOS"* ]]; then
    # --------------------------------------------------------------------------
    [[ -n $(yum list installed | grep -i ^flatpak) ]] || yum install -y flatpak
    # --------------------------------------------------------------------------
elif [[ *"${CUR_VER}"* == *"rocky"* ]]; then
    # --------------------------------------------------------------------------
    [[ -n $(dnf list installed | grep -i ^flatpak) ]] || dnf install -y flatpak;
    # --------------------------------------------------------------------------
fi

add_flathub;
# ==============================================================================

exit 0