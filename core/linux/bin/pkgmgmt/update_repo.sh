#!/bin/bash

# update_repo ==================================================================
# bash ${BIN_DIR}/pkgmgmt/update_repo.sh;
# ==============================================================================


# ENV ==========================================================================
# ------------------------------------------------------------------------------
# core/linux/bin/pkgmgmt
ROOT_DIR="$(dirname "$(realpath "$0")")"

# core/linux/bin
BIN_DIR="${ROOT_DIR}/.."
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);
# ------------------------------------------------------------------------------
# ==============================================================================


# Func =========================================================================
function add_epel_repo_for_dnf()
{
    # --------------------------------------------------------------------------
    if [[ -n $(dnf list installed | grep -i ^epel-release) ]]; then
        return
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    dnf install -y epel-release;
    dnf check-update;
    # --------------------------------------------------------------------------
}

function add_rpmfusion_free_repo_for_dnf()
{
    # --------------------------------------------------------------------------
    if [[ -n $(dnf list installed | grep -i ^rpmfusion-free-release) ]]; then
        return
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    dnf install -y rpmfusion-free-release;
    dnf check-update;
    # --------------------------------------------------------------------------
}

function set_crb_enabled_for_dnf()
{
    # --------------------------------------------------------------------------
    if [[ -n $(dnf repolist | grep -i ^crb) ]]; then
        return
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    if [[ *"${CUR_VER}"* == *"VERSION_ID=\"8"* ]]; then     # rocky8
        # powertools
        dnf config-manager --set-enabled powertools
    else                                                    # rocky9
        # CodeReady Builder
        dnf config-manager --set-enabled crb
    fi
    dnf check-update;
    # --------------------------------------------------------------------------
}
# ==============================================================================



# Main =========================================================================
if [[ *"${CUR_VER}"* == *"debian"* ]] || [[ *"${CUR_VER}"* == *"ubuntu"* ]]; then
    # --------------------------------------------------------------------------
    apt update;
    # --------------------------------------------------------------------------

elif [[ *"${CUR_VER}"* == *"CentOS"* ]] || [[ *"${CUR_VER}"* == *"rocky"* ]]; then
    # --------------------------------------------------------------------------
    add_epel_repo_for_dnf;
    add_rpmfusion_free_repo_for_dnf;
    set_crb_enabled_for_dnf;
    # --------------------------------------------------------------------------
fi
# ==============================================================================

exit 0