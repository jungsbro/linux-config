# Funcs ========================================================================
function set_xprofile_enable()
{
    # --------------------------------------------------------------------------
    # only working for fedora and rhel
    local cur_release=$(cat /etc/*-release 2>/dev/null);

    if [[ "${cur_release}" != *"Fedora"* ]] && [[ "${cur_release}" != *"CentOS"* ]] && [[ "${cur_release}" != *"rocky"* ]]; then
        return 0
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    local dst_xinitrc_path="/etc/X11/xinit/xinitrc.d/99-user-xprofile.sh";

    local cmd='#!/bin/sh

if [ -f "$HOME/.xprofile" ]; then
    . "$HOME/.xprofile"
fi
if [ -f "$HOME/.xsessionrc" ]; then
    . "$HOME/.xsessionrc"
fi

'
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    if [[ -f "${dst_xinitrc_path}" ]]; then
        return 0
    fi

    echo "${cmd}" > "${dst_xinitrc_path}";
    chmod +x "${dst_xinitrc_path}";
    # --------------------------------------------------------------------------
}
