#!/bin/bash

# usage ========================================================================
# bash ${CORE_BIN_DIR}/wmde/de/kde/set_panel_vdesktop_for_kde.sh
# ==============================================================================


# ENV ==========================================================================
# ------------------------------------------------------------------------------
# /core/linux/bin/wmde/de/kde
CUR_DIR="$(dirname "$(realpath "$0")")"

ROOT_DIR="${CUR_DIR}/../../../../../.."

# core/linux/bin
CORE_BIN_DIR="${ROOT_DIR}/core/linux/bin"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
CUR_USER=${1};
HOME_DIR=$(eval echo ~${CUR_USER});

CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);

CUR_WMDE=$(ls /usr/bin/*session);
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
# vi ~/.config/kwinrc
# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
# [Desktops]
# Number=4
# Rows=2
# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

FILE="kwinrc"
# ------------------------------------------------------------------------------
# ==============================================================================


# Funcs ========================================================================
function set_panel_vdesktop()
{
    # --------------------------------------------------------------------------
    # 가상 데스크톱 개수를 4개로 설정
    kwriteconfig6 --file ${FILE} --group Desktops --key Number 4

    # 행(Rows)의 개수를 2개로 설정 (2행 2열 배치가 됩니다)
    kwriteconfig6 --file ${FILE} --group Desktops --key Rows 2
    # --------------------------------------------------------------------------
}
# ==============================================================================


# Main =========================================================================
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    # --------------------------------------------------------------------------
    set_panel_vdesktop;
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    # source ${CORE_BIN_DIR}/wmde/de/kde/set_funcs_for_kde.sh && restart_kwin;
    # --------------------------------------------------------------------------
fi
# ==============================================================================