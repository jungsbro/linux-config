# ENV ==========================================================================
# ------------------------------------------------------------------------------
# /core/linux/bin/wmde/de/kde
CUR_DIR="$(dirname "$(realpath "${BASH_SOURCE[0]}")")"

ROOT_DIR="${CUR_DIR}/../../../../../.."

# core/linux/bin
CORE_BIN_DIR="${ROOT_DIR}/core/linux/bin"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
CUR_USER=${1};
HOME_DIR=$(eval echo ~${CUR_USER});

CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);

CUR_WMDE=$(ls /usr/bin/*session);
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
# vi ~/.config/plasmashellrc
# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
# [PlasmaViews][Panel 2]
# floating=0
# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~


FILE="plasmashellrc"

# PANEL_ID=$(grep -o 'PlasmaViews\]\[Panel [0-9]*\]' ~/.config/plasmashellrc | cut -d'[' -f2 | cut -d']' -f1 | cut -d' ' -f2 | sort -u)
PANEL_ID=$(grep -o 'PlasmaViews\]\[Panel [0-9]*\]' ~/.config/${FILE} | cut -d'[' -f2 | cut -d']' -f1 | cut -d' ' -f2 | sort -u)
# PlasmaView][Panel 2]  >>  Panel 2]  >>  Panel 2  >>  2
# ------------------------------------------------------------------------------
# ==============================================================================


# Funcs ========================================================================
function set_panel_float()
{
    # --------------------------------------------------------------------------
    if [ -n "${PANEL_ID}" ]; then
        echo "PANEL ID: ${PANEL_ID} 에 설정을 적용합니다."

        # ----------------------------------------------------------------------
        kwriteconfig6 --file plasmashellrc --group "PlasmaViews" --group "Panel ${PANEL_ID}" --key "floating" 0
        # ----------------------------------------------------------------------

    else
        echo "ID를 찾지 못했습니다."
    fi
    # --------------------------------------------------------------------------
}
# ==============================================================================


# Main =========================================================================
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    # --------------------------------------------------------------------------
    set_panel_float;
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    # source ${CORE_BIN_DIR}/wmde/de/kde/set_funcs_for_kde.sh && restart_plasmashell;
    # --------------------------------------------------------------------------
fi
