# Funcs ========================================================================
function set_theme_icon()
{
    if [[ -d "${ICON_DIR}" ]]; then
        # ----------------------------------------------------------------------
        # 아이콘 테마를 Papirus로 설정
        # 기본 Papirus 외에도 Papirus-Dark, Papirus-Light 등이 있으니 취향껏 선택 가능합니다.
        kwriteconfig6 --file "${FILE}" --group Icons --key Theme "${ICON_NAME}"
        # ----------------------------------------------------------------------
    fi
}


function execute_main()
{
    # --------------------------------------------------------------------------
    set_theme_icon;
