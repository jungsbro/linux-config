function get_sel_plugin()
{
    # --------------------------------------------------------------------------
    # get_sel_plugin "xfce4-panel" "clock";

    # /plugins/plugin-8                      clock
    # /plugins/plugin-8    >>   plugin-8
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    # xfce4-panel
    local ch="${1}"

    # clock
    local kwd="${2}"
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    # /plugins/plugin-8                      clock

    local sel_prop=$(xfconf-query -c "${ch}" -l -v | grep -i "${kwd}" 2>/dev/null);
    if [[ -z "${sel_prop}" ]]; then
        return 0
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    # /plugins/plugin-8                      clock

    # 1    2      3
    # /plugins/plugin-8    >>   plugin-8

    local sel_plugin=$(echo "${sel_prop}" | awk '{print $1}' | cut -d '/' -f 3 2>/dev/null);
    if [[ -z "${sel_plugin}" ]]; then
        return 0
    fi
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    # plugin-11
    echo "${sel_plugin}"
    # --------------------------------------------------------------------------
}


function set_prop_value()
{
    # env ----------------------------------------------------------------------
    local ch="${1}"
    local prop="${2}"
    local typ="${3}"
    local val="${4}"

    # xfconf-query -c "xfce4-keyboard-shortcuts" -p "/xfwm4/custom/<Super>Up"
    # -c : --chanel
    # -p : --property
    local cmd="xfconf-query -c ${ch} -p ${prop}"
    # --------------------------------------------------------------------------

    # reset property (remove property) -----------------------------------------
    # xfconf-query -c "xfce4-keyboard-shortcuts" -p "/xfwm4/custom/<Super>Up" -r
    # -r : --reset
    `${cmd} -r`
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    if [[ -z "${val}" ]]; then
        return 0
    fi
    # --------------------------------------------------------------------------

    # set property value (create and set) --------------------------------------
    # xfconf-query -c "xfce4-keyboard-shortcuts" -p "/xfwm4/custom/<Super>Up" --create -t "string" -s "fill_window_key"
    # -n : --create
    # -t : type
    # -s : --set
    `${cmd} -n -t "${typ}" -s "${val}"`
    echo "${cmd} -n -t \"${typ}\" -s \"${val}\""
    # --------------------------------------------------------------------------
}
