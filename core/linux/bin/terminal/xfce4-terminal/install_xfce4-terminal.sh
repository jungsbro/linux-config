#!/bin/bash

# usage ========================================================================
# bash ${CORE_BIN_DIR}/terminal/xfce4-terminal/install_xfce4-terminal.sh ${CUR_USER};
# ==============================================================================


# ENV ==========================================================================
# ------------------------------------------------------------------------------
# /core/linux/bin/terminal/xfce4-terminal
CUR_DIR="$(dirname "$(realpath "${BASH_SOURCE[0]}")")"

ROOT_DIR="${CUR_DIR}/../../../../.."

# core/linux/bin
CORE_BIN_DIR="${ROOT_DIR}/core/linux/bin"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
CUR_USER=${1};
HOME_DIR=$(eval echo ~${CUR_USER});

CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);

CUR_WMDE=$(ls /usr/bin/*session);
# ------------------------------------------------------------------------------
# ==============================================================================


# Funcs ========================================================================
function copy_config_to_home()
{
    # --------------------------------------------------------------------------
    local fname=""
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    local src_dir="${CUR_DIR}/config";
    local src_path=""
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    local dst_dir=""
    local dst_path="";

    local dst_path_list=(
        "${HOME_DIR}/.config/xfce4/terminal/terminalrc"
        "${HOME_DIR}/.config/xfce4/xfconf/xfce-perchannel-xml/xfce4-terminal.xml"
    )
    # --------------------------------------------------------------------------

    # --------------------------------------------------------------------------
    for dst_path in "${dst_path_list[@]}";
    do
        # ----------------------------------------------------------------------
        fname=$(basename "${dst_path}");
        # ----------------------------------------------------------------------

        # ----------------------------------------------------------------------
        src_path="${src_dir}/${fname}";

        if [[ ! -f "${src_path}" ]]; then
            continue;
        fi
        # ----------------------------------------------------------------------

        # ----------------------------------------------------------------------
        if [[ -f "${dst_path}" ]]; then
            continue;
        fi

        dst_dir=$(dirname "${dst_path}");

        if [[ ! -d "${dst_dir}" ]]; then
            su - ${CUR_USER} -c "mkdir -p ${dst_dir}";
        fi
        # ----------------------------------------------------------------------

        # ----------------------------------------------------------------------
        su - ${CUR_USER} -c "cp -f ${src_path} ${dst_path}";
        # ----------------------------------------------------------------------
    done
}
# ==============================================================================


# Main =========================================================================
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then

    if [[ *"${CUR_VER}"* == *"archlinux"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(pacman -Q | grep -i ^xfce4-terminal) ]] || pacman -S --needed --noconfirm xfce4-terminal;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"debian.org"* ]] || [[ *"${CUR_VER}"* == *"ubuntu"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(apt list --installed | grep -i ^xfce4-terminal) ]] || apt install -y --no-install-recommends xfce4-terminal;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"Fedora"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^xfce4-terminal) ]] || dnf install -y xfce4-terminal;
        # ----------------------------------------------------------------------

    elif [[ *"${CUR_VER}"* == *"CentOS"* ]] || [[ *"${CUR_VER}"* == *"rocky"* ]]; then
        # ----------------------------------------------------------------------
        [[ -n $(dnf list --installed | grep -i ^epel-release) ]] || bash ${CORE_BIN_DIR}/pkgmgmt/update_repo.sh;
        [[ -n $(dnf list --installed | grep -i ^xfce4-terminal) ]] || dnf install -y xfce4-terminal;
        # ----------------------------------------------------------------------
    fi

    copy_config_to_home;

fi
# ==============================================================================

# EOF ==========================================================================
source ${CORE_BIN_DIR}/pkgmgmt/install_pkgmgmt_funcs.sh && display_msg "";
# ==============================================================================