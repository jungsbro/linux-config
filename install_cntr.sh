# ENV ==========================================================================
# ------------------------------------------------------------------------------
ROOT_DIR="$(dirname "$(realpath "$0")")"

# core/linux/bin
CORE_BIN_DIR="${ROOT_DIR}/core/linux/bin"
# ------------------------------------------------------------------------------

# CUR_USER ---------------------------------------------------------------------
# CUR_USER="jungs";
CUR_USER="${1}"

while [[ -z "${CUR_USER}" ]]
do
    echo "Username not provided."
    read -p "Please input username : " CUR_USER
done

# echo "User selected: ${CUR_USER}"
# ------------------------------------------------------------------------------

# ------------------------------------------------------------------------------
HOME_DIR=$(eval echo ~"${CUR_USER}");

CUR_VER=$(cat /etc/*-release 2> /dev/null);

CUR_ARCH=$(uname -m);

CUR_WMDE=$(ls /usr/bin/*session 2> /dev/null || true);
# ------------------------------------------------------------------------------
# ==============================================================================


# Funcs ========================================================================
function execute_main()
{
    # update -------------------------------------------------------------------
    bash ${CORE_BIN_DIR}/pkgmgmt/update_repo.sh;
    # --------------------------------------------------------------------------

    # graphic driver -----------------------------------------------------------
    bash ${CORE_BIN_DIR}/gpu/install_gpu.sh "${CUR_USER}";
    bash ${CORE_BIN_DIR}/gpu/install_gpu_top.sh;
    # --------------------------------------------------------------------------

    # container ----------------------------------------------------------------
    bash ${CORE_BIN_DIR}/gpu/install_gpu_nvidia-container-toolkit.sh;
    bash ${CORE_BIN_DIR}/container/install_podman.sh;
    bash ${CORE_BIN_DIR}/container/install_distrobox.sh;
    # --------------------------------------------------------------------------
}
# ==============================================================================


# Main =========================================================================
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    execute_main;

    source ${CORE_BIN_DIR}/pkgmgmt/install_pkgmgmt_funcs.sh && show_msg "";
fi
